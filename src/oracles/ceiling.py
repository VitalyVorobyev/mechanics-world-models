"""Rung 3 ceiling: the true cartpole dynamics under our integrator.

The dynamics oracle compares *learned* models; this one asks what error a
perfectly learned Lagrangian would still have. It takes MuJoCo's own
acceleration (mass matrix, bias, damping, actuator) at each state — with the
slider joint limit disabled, because a smooth Lagrangian cannot represent
it — and integrates with the same semi-implicit Euler step the models use,
at the frame interval with ``n`` substeps. The data were generated by RK4 at
0.01 s with an active rail limit, so the residual separates integrator error
(falls with substeps) from rail-contact error (only in windows that reach
the limit).
"""

from __future__ import annotations

from typing import Sequence

import numpy as np

from envs.dm_control_pixels import DmControlPixelEnv, PixelEnvConfig
from oracles.common import Criterion, OracleResult, StateEpisodes, pose_features

SLIDER_LIMIT = 1.8


class TrueAcceleration:
    """``qacc(q, qdot, u)`` from MuJoCo with the joint limit switched off."""

    def __init__(self, physics_param_scales: dict[str, float] | None = None) -> None:
        import mujoco

        self._env = DmControlPixelEnv(PixelEnvConfig(physics_param_scales=physics_param_scales))
        physics = self._env._env.physics
        self._model = physics.model.ptr
        self._data = physics.data.ptr
        self._model.opt.disableflags |= int(mujoco.mjtDisableBit.mjDSBL_LIMIT)
        self._mujoco = mujoco

    def __call__(self, q: np.ndarray, qdot: np.ndarray, u: np.ndarray) -> np.ndarray:
        out = np.empty_like(q)
        for i in range(q.shape[0]):
            self._data.qpos[:] = q[i]
            self._data.qvel[:] = qdot[i]
            self._data.ctrl[:] = u[i]
            self._mujoco.mj_forward(self._model, self._data)
            out[i] = self._data.qacc
        return out

    def close(self) -> None:
        self._env.close()


def integrate(
    accel: TrueAcceleration, q: np.ndarray, qdot: np.ndarray, actions: np.ndarray, dt: float, n_substeps: int,
) -> np.ndarray:
    """``q, qdot [N, 2]``, ``actions [N, H, A]`` -> ``q [N, H, 2]`` by semi-implicit Euler."""

    h = dt / n_substeps
    out = []
    for step in range(actions.shape[1]):
        for _ in range(n_substeps):
            qdot = qdot + h * accel(q, qdot, actions[:, step])
            q = q + h * qdot
        out.append(q)
    return np.stack(out, axis=1)


def near_rail_mask(qpos: np.ndarray, starts: np.ndarray, horizon: int, margin: float) -> np.ndarray:
    """``True`` for windows whose cart comes within ``margin`` of the rail limit."""

    reach = np.stack([np.abs(qpos[:, s : s + horizon + 1, 0]).max(axis=1) for s in starts], axis=1)
    return reach.reshape(-1) >= SLIDER_LIMIT - margin


def window_starts(frames: int, horizon: int, stride: int) -> np.ndarray:
    return np.arange(0, frames - horizon, stride)


def run_dynamics_ceiling(
    episodes: dict[str, tuple[StateEpisodes, dict[str, float] | None]],
    *,
    substeps: Sequence[int] = (1, 2, 4),
    horizons: Sequence[int] = (10, 20, 50),
    stride: int = 10,
    rail_margin: float = 0.2,
    log=print,
) -> OracleResult:
    """Pose error of the true dynamics, per dataset, substep count and rail subset."""

    horizon = max(horizons)
    metrics: dict[str, float] = {}
    for name, (data, scales) in episodes.items():
        accel = TrueAcceleration(scales)
        try:
            frames = data.qpos.shape[1] - 1
            starts = window_starts(frames, horizon, stride)
            q0 = data.qpos[:, starts].reshape(-1, 2)
            v0 = data.qvel[:, starts].reshape(-1, 2)
            act = np.stack([data.actions[:, s : s + horizon] for s in starts], axis=1).reshape(-1, horizon, 1)
            tgt = np.stack([data.qpos[:, s + 1 : s + 1 + horizon] for s in starts], axis=1).reshape(-1, horizon, 2)
            rail = near_rail_mask(data.qpos, starts, horizon, rail_margin)
            metrics[f"{name}.near_rail_fraction_h{horizon}"] = float(rail.mean())
            for n in substeps:
                pred = integrate(accel, q0, v0, act, data.frame_dt, n)
                dev = np.abs(pose_features(pred) - pose_features(tgt)).mean(axis=-1)  # [N, H]
                for h in horizons:
                    metrics[f"{name}.sub{n}.dev_h{h}"] = float(dev[:, h - 1].mean())
                    metrics[f"{name}.sub{n}.free.dev_h{h}"] = float(dev[~rail, h - 1].mean())
                log(
                    f"{name} substeps={n}: "
                    + "  ".join(
                        f"h{h} {metrics[f'{name}.sub{n}.dev_h{h}']:.4f} (free {metrics[f'{name}.sub{n}.free.dev_h{h}']:.4f})"
                        for h in horizons
                    ),
                )
        finally:
            accel.close()

    first = next(iter(episodes))
    best = max(substeps)
    return OracleResult(
        name="dynamics_ceiling",
        hypotheses=["H1b"],
        question="How accurate is the true cartpole dynamics under our integrator, with and without rail contacts?",
        config={
            "substeps": list(substeps),
            "horizons": list(horizons),
            "stride": stride,
            "rail_margin": rail_margin,
            "datasets": {name: scales for name, (_, scales) in episodes.items()},
        },
        metrics=metrics,
        criteria=[
            Criterion(
                f"{first}.sub{best}.free.dev_h20", "<=", 0.005,
                "true dynamics away from the rail are resolvable well below the cart-mass effect (0.027)",
            ),
        ],
        notes=[
            "Errors are mean |Δ(x, cos θ, sin θ)| at the horizon, same unit as the intervention oracle.",
            "'free' excludes windows whose cart comes within rail_margin of the ±1.8 m slider limit.",
        ],
    )

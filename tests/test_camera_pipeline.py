"""Camera geometry, keypoint reader and fixed-lag estimator (E-008)."""

from __future__ import annotations

import numpy as np
import torch

from control.camera import FULL_VIEW, CameraSpec, render_states
from control.estimator import FixedLagEstimator, integrate, learned_dynamics, mujoco_dynamics
from control.keypoints import pose_error_metrics, read_poses, sample_states, train_reader
from oracles.dynamics import DynamicsWrapper


def test_default_camera_matches_known_scale() -> None:
    assert abs(CameraSpec().pixels_per_metre - 25.35) < 0.01


def test_keypoints_round_trip_to_pose() -> None:
    q = sample_states(100, seed=0)
    for spec in (CameraSpec(), FULL_VIEW):
        back = spec.pose(spec.keypoints(q))
        assert np.allclose(back[:, 0], q[:, 0])
        assert np.allclose(np.angle(np.exp(1j * (back[:, 1] - q[:, 1]))), 0.0, atol=1e-9)


def test_full_view_keeps_rail_and_pole_in_frame() -> None:
    corners = np.array([[1.8, np.pi / 2], [-1.8, -np.pi / 2], [1.8, 0.0], [-1.8, np.pi]])
    assert np.all(np.abs(FULL_VIEW.keypoints(corners)) < 1.0)


def test_projected_pole_tip_is_on_the_pole() -> None:
    """The rendered pole colour sits under the projected tip (upright pole, cart at x = 1)."""

    spec = FULL_VIEW
    image = render_states(np.array([[1.0, 0.0]]), spec)[0].astype(int)
    pole = (image[..., 0] - image[..., 2] > 50) & (image[..., 0] > 100)
    col, row = (spec.keypoints(np.array([1.0, 0.0]))[1] + 1.0) * (spec.image_size - 1) / 2.0
    assert pole[int(round(row)) + 1, int(round(col)) - 1 : int(round(col)) + 2].any()


def test_reader_trains_and_reads() -> None:
    q = sample_states(64, seed=1)
    images = render_states(q, FULL_VIEW)
    model, loss = train_reader(images, FULL_VIEW.keypoints(q), steps=3, batch_size=8, log=lambda _: None)
    metrics = pose_error_metrics(read_poses(model, images, FULL_VIEW), q, FULL_VIEW)
    assert np.isfinite(loss) and np.isfinite(metrics["theta_median_deg"])


def test_estimator_recovers_velocity_of_its_own_model() -> None:
    """Noise-free poses generated by the estimator's own model: the velocity comes back."""

    torch.manual_seed(0)
    model = DynamicsWrapper("mlp", dt=0.02, n_substeps=2).eval()
    actions = np.random.default_rng(0).uniform(-1, 1, size=(40, 1))
    q, qdot = np.array([[0.0, 3.0]]), np.array([[0.3, -1.0]])
    estimator = FixedLagEstimator(learned_dynamics(model), window=10)
    for k in range(40):
        if k:
            q, qdot = integrate(model, q, qdot, actions[k - 1][None, None])
        state = estimator.update(q[0], actions[k - 1] if k else None)
    assert estimator.rejected == 0
    assert np.abs(state[1] - qdot[0]).max() < 0.05


def test_mujoco_dynamics_matches_env() -> None:
    from envs.dm_control_pixels import DmControlPixelEnv, PixelEnvConfig

    env = DmControlPixelEnv(PixelEnvConfig(seed=2, action_repeat=2))
    env.reset_without_render()
    start = env.physics_state()
    dynamics = mujoco_dynamics(env.physics.model.ptr, action_repeat=2)
    actions = np.random.default_rng(3).uniform(-1, 1, size=(1, 15, 1))
    poses = dynamics.rollout(start["qpos"][None], start["qvel"][None], actions)
    q_end, v_end = dynamics.integrate(start["qpos"][None], start["qvel"][None], actions)
    for k in range(15):
        state, _ = env.step_state(actions[0, k])
        assert np.allclose(poses[0, k], state["qpos"], atol=1e-9)
    assert np.allclose(q_end[0], state["qpos"]) and np.allclose(v_end[0], state["qvel"])
